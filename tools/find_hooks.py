#!/usr/bin/env python3
"""Find Bedrock functions in libminecraftpe.so (arm64) and write <event>.txt byte signatures + Signatures.inc.
usage: find_hooks.py <libminecraftpe.so> <out-dir>

The library is stripped, but it embeds readable names. Three kinds of anchor are used (see docs/HOOKS.md):
  fn    code loading a function-name string (profiler/assert strings)         -> that function
  slot  string reached through a data-table pointer (R_AARCH64_RELATIVE)      -> function using that slot
  evt   telemetry event name ("BlockBroken"): the *virtual* function that references it (EventingProducer::fireEvent*)
A pattern is kept only when it matches exactly one place in .text."""
import pathlib, sys
from binxref import Bin, unique_pattern

# event -> (kind, string, pick) ; pick = which candidate (sorted by address) after the filter
HOOKS = {
 "world.join":    ("fn",   "void ClientInstance::_joinWorldInProgressSubclient(brstd::optional<ConnectionContextInfo>)", 0),
 "world.leave":   ("fn",   "virtual void ClientInstance::requestLeaveGame(bool, bool)", 0),
 "player.login":  ("fn",   "void ServerNetworkHandler::_onSubClientAuthenticated(const NetworkIdentifier &, std::shared_ptr<SubClientLoginPacket>, const PlayerAuthenticationInfo &)", 0),
 "player.tick":   ("slot", "virtual void Player::tickWorld(const Tick &)", 0),
 "level.tick":    ("slot", "virtual void Level::tick()", 0),
 "game.update":   ("slot", "void MinecraftGame::_update()", 0),     # the virtual wrapper that runs once per frame
 "block.break":   ("evt",  "BlockBroken", 0),
 "block.place":   ("evt",  "BlockPlaced", 0),
 "mob.kill":      ("evt",  "MobKilled", 0),
 "player.die":    ("evt",  "PlayerDied", 0),
 "mob.interact":  ("evt",  "MobInteracted", 0),
 "item.use":      ("evt",  "ItemUsed", 0),
 "item.drop":     ("evt",  "ItemDropped", 0),
 "item.craft":    ("evt",  "ItemCrafted", 0),
 "player.teleport": ("evt", "PlayerTeleported", 0),
 "chat.send":     ("evt",  "PlayerMessage", 1),                      # 2nd virtual user: the one that only fires the event
 "chat.display":  ("fn_str", "chat.type.text", 0),
}

def candidates(b, kind, s):
    sv = b.find_string(s)
    if sv < 0: return []
    fns = set(b.fn(int(r)) for r in b.refs_to(sv))
    for p in b.data_ptrs_to(sv):
        fns |= set(b.fn(int(r)) for r in b.refs_to(p - 64, p + 8))
    fns = sorted(fns)
    if kind in ("evt", "slot"): fns = [f for f in fns if b.data_ptrs_to(f)]   # virtual functions only
    return fns

def main():
    b = Bin(sys.argv[1]); out = pathlib.Path(sys.argv[2]); out.mkdir(parents=True, exist_ok=True)
    inc = []
    for ev, (kind, s, pick) in HOOKS.items():
        c = candidates(b, kind, s)
        if kind in ("fn",) and len(c) != 1: print(f"{ev:16} need exactly 1 function, got {len(c)}"); continue
        if kind == "slot" and ev == "game.update": c = [f for f in c if b.fn_size(f) < 2000]
        if pick >= len(c): print(f"{ev:16} no candidate (found {len(c)})"); continue
        fa = c[pick]
        pat, n = unique_pattern(b, fa)
        if not pat: print(f"{ev:16} fn=0x{fa:x} no unique pattern"); continue
        (out / f"{ev}.txt").write_text(pat + "\n"); inc.append(f'{{"{ev}", "{pat}"}},')
        print(f"{ev:16} ok  fn=0x{fa:x} size={b.fn_size(fa)} pattern={n} insns")
    (out / "Signatures.inc").write_text("// generated by tools/find_hooks.py\n" + "\n".join(inc) + "\n")

if __name__ == "__main__": main()
